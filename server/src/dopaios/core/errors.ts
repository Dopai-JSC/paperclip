// I-5 — danh mục mã lỗi ERR-* tập trung của tầng Dopaios (mẫu hiện thực số 3:
// ERR-<DANH-MỤC>[-<CHI-TIẾT>]; mã đã phát hành không đổi nghĩa). Mọi mã ERR-*
// dùng trong core/ phải có mặt ở đây — errors.test.ts cưỡng chế fail-closed.

export class CommandPayloadMismatchError extends Error {
  constructor(commandId: string) {
    super(`Command ${commandId} was already executed with a different payload`);
    this.name = "CommandPayloadMismatchError";
  }
}

export class CommandRejectedError extends Error {
  constructor(
    readonly code: string,
    message: string,
  ) {
    super(message);
    this.name = "CommandRejectedError";
  }
}

